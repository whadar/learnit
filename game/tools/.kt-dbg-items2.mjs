import { chromium } from 'playwright';
const CHROME = '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
const b = await chromium.launch({ executablePath: CHROME, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox', '--disable-dev-shm-usage'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
p.on('pageerror', e => console.log('PAGEERROR:', e.message, '\n', (e.stack || '').split('\n').slice(0, 6).join('\n')));
p.on('console', m => { const t = m.text(); if (m.type() === 'error' || /error|fail|shader|program|THREE/i.test(t)) console.log('C[' + m.type() + ']:', t.slice(0, 1500)); });
await p.goto('http://127.0.0.1:4173/?review=1&audio=0&q=high', { waitUntil: 'load', timeout: 180000 });
await p.waitForFunction(() => window.__game && (window.__game.ready || window.__game.error), null, { timeout: 600000 });
console.log('READY err=', await p.evaluate(() => window.__game.error));
await p.evaluate(() => window.__game.setView('itemChaos'));
await p.evaluate(() => new Promise(r => { let i = 0; const s = () => (++i >= 10 ? r() : requestAnimationFrame(s)); requestAnimationFrame(s); }));
await p.screenshot({ path: 'shots/dbg-itemChaos.png' });
console.log('SHOTDONE');
await b.close();
process.exit(0);
